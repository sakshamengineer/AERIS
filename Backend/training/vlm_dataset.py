import json
import random
from pathlib import Path

# ============================================================
# CONFIGURATION
# ============================================================

MAX_EXAMPLES = 2000
RANDOM_SEED = 42

PROJECT_ROOT = Path(__file__).resolve().parent.parent

MANIFEST_PATH = (
    PROJECT_ROOT
    / "data"
    / "bigearthnet"
    / "training_manifest_large.json"
)

PROCESSED_DIR = (
    PROJECT_ROOT
    / "data"
    / "bigearthnet"
    / "processed"
)

OUTPUT_PATH = (
    PROJECT_ROOT
    / "data"
    / "bigearthnet"
    / "vlm_training.json"
)


# ============================================================
# LOAD MANIFEST
# ============================================================

def load_manifest():
    print("=" * 60)
    print("BUILDING VLM TRAINING DATASET")
    print("=" * 60)

    if not MANIFEST_PATH.exists():
        raise FileNotFoundError(
            f"Manifest not found:\n{MANIFEST_PATH}"
        )

    with open(MANIFEST_PATH, "r", encoding="utf-8") as f:
        manifest = json.load(f)

    return manifest


# ============================================================
# BUILD EXAMPLES
# ============================================================

def build_examples(manifest):

    patches = manifest.get("patches", [])

    print(f"\nUnique patches in manifest: {len(patches)}")

    examples = []

    for patch in patches:

        patch_id = patch.get("patch_id")
        s1_name = patch.get("s1_name")

        if not patch_id:
            continue

        # Expected RGB image generated by bigearthnet_s2_loader.py
        image_path = PROCESSED_DIR / f"{patch_id}_rgb.png"

        # Skip patches whose RGB image does not exist
        if not image_path.exists():
            continue

        annotations = patch.get("annotations", [])

        for annotation in annotations:

            question = annotation.get("input")
            answer = annotation.get("output")

            task_type = annotation.get("type", "").lower()

            if not question or answer is None:
                continue

            # ------------------------------------------------
            # Convert BigEarthNet annotation type
            # into our task names
            # ------------------------------------------------

            if task_type == "captioning":
                task = "captioning"

            elif task_type == "bounding box":
                task = "grounding"

            else:
                # Binary, multiple choice, etc.
                task = "vqa"

            examples.append(
                {
                    "image": str(
                        image_path.relative_to(PROJECT_ROOT)
                    ),
                    "patch_id": patch_id,
                    "s1_name": s1_name,
                    "task": task,
                    "instruction": question,
                    "answer": answer,
                    "annotation_type": annotation.get("type"),
                    "category": annotation.get("category"),
                }
            )

    print(f"Total available annotations: {len(examples)}")

    # ========================================================
    # SHUFFLE AND LIMIT
    # ========================================================

    random.seed(RANDOM_SEED)
    random.shuffle(examples)

    selected_examples = examples[:MAX_EXAMPLES]

    print(f"Selected examples: {len(selected_examples)}")

    # ========================================================
    # TASK DISTRIBUTION
    # ========================================================

    distribution = {}

    for example in selected_examples:
        task = example["task"]
        distribution[task] = distribution.get(task, 0) + 1

    print("\nTask distribution:")

    for task, count in sorted(distribution.items()):
        print(f"  {task}: {count}")

    return selected_examples


# ============================================================
# SAVE DATASET
# ============================================================

def save_dataset(examples):

    OUTPUT_PATH.parent.mkdir(
        parents=True,
        exist_ok=True
    )

    with open(
        OUTPUT_PATH,
        "w",
        encoding="utf-8"
    ) as f:

        json.dump(
            examples,
            f,
            indent=2,
            ensure_ascii=False
        )

    print(f"\nDataset saved to:")
    print(OUTPUT_PATH)


# ============================================================
# PREVIEW
# ============================================================

def show_preview(examples):

    print("\n" + "=" * 60)
    print("FIRST 5 TRAINING EXAMPLES")
    print("=" * 60)

    for i, example in enumerate(examples[:5], start=1):

        print(f"\nExample {i}")
        print("-" * 40)

        print(f"Task:        {example['task']}")
        print(f"Patch:       {example['patch_id']}")
        print(f"Instruction: {example['instruction']}")
        print(f"Answer:      {example['answer']}")


# ============================================================
# MAIN
# ============================================================

def main():

    manifest = load_manifest()

    examples = build_examples(manifest)

    save_dataset(examples)

    show_preview(examples)

    print("\n" + "=" * 60)
    print("VLM DATASET CREATION SUCCESSFUL")
    print("=" * 60)


if __name__ == "__main__":
    main()